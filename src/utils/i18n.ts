const SUPPORTED_SET = new Set<AppLanguage>(LANGUAGE_OPTIONS.map((o) => o.code));

export function isAppLanguage(val: unknown): val is AppLanguage {
  return typeof val === 'string' && SUPPORTED_SET.has(val as AppLanguage);
}

export function getLanguageOption(lang: AppLanguage): LanguageOption {
  return LANGUAGE_OPTIONS.find((o) => o.code === lang) ?? LANGUAGE_OPTIONS[0];
}

export function resolveBrowserLanguage(
  navigatorLanguages?: readonly string[] | string | null
): AppLanguage {
  const rawList: string[] = Array.isArray(navigatorLanguages)
    ? [...navigatorLanguages]
    : typeof navigatorLanguages === 'string' && navigatorLanguages.trim()
    ? [navigatorLanguages]
    : [];

  for (const tag of rawList) {
    if (typeof tag !== 'string') continue;
    const primary = tag.trim().toLowerCase().split(/[-_]/)[0];
    if (isAppLanguage(primary)) {
      return primary;
    }
  }
  return 'en';
}

export function getInitialLanguage(
  storage?: Pick<Storage, 'getItem'> | null,
  navigatorLanguages?: readonly string[] | string | null
): AppLanguage {
  try {
    const saved = storage?.getItem(LANGUAGE_STORAGE_KEY);
    if (isAppLanguage(saved)) {
      return saved;
    }
  } catch {
    // Ignore restricted storage access
  }
  return resolveBrowserLanguage(navigatorLanguages);
}

export function formatLocalizedNumber(n: number, lang: AppLanguage): string {
  const opt = getLanguageOption(lang);
  try {
    return new Intl.NumberFormat(opt.locale).format(n);
  } catch {
    return String(n);
  }
}

export function getDisplayName(
  figure: { name: string; englishName?: string },
  lang: AppLanguage
): string {
  if (lang === 'fa') {
    return figure.name;
  }
  return (figure.englishName && figure.englishName.trim()) || figure.name;
}

export function getSecondaryName(
  figure: { name: string; englishName?: string },
  lang: AppLanguage
): string | null {
  if (lang === 'fa') {
    return figure.englishName && figure.englishName !== figure.name
      ? figure.englishName
      : null;
  }
  return null;
}

