import type { DislikeEvent, FigureCategory, FigureSuggestion, PublicFigure } from '../src/types';

function makeFigure(
  id: string,
  name: string,
  englishName: string,
  category: FigureCategory,
  country: string,
  wikiTitleFa: string,
  wikiTitleEn: string,
  dislikes: number,
  shortBio: string,
  index: number
): PublicFigure {
  const created = new Date(Date.UTC(2026, 0, 1 + Math.floor(index / 6), (index % 6) * 3, 0, 0));
  return {
    id,
    name,
    englishName,
    category,
    country,
    shortBio,
    imageUrl: `/api/figures/${id}/photo`,
    wikiTitleFa,
    wikiTitleEn,
    dislikes,
    createdAt: created.toISOString(),
  };
}

